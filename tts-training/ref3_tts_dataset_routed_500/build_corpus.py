# ===== 组合生成 =====

def generate_corpus():
    lines = set()

    # 直接添加所有固定语料
    for s in (GREETINGS + PERSONA + GAME_LINES + KNOWLEDGE +
              STORIES + QUESTIONS + FESTIVALS + MEMORY_LINES +
              SHORT_REPLIES + LONG_SENTENCES +
              EMOTION_HAPPY + EMOTION_SAD + EMOTION_SURPRISE +
              EMOTION_ANGER + EMOTION_NEUTRAL):
        s = s.strip()
        if s:
            lines.add(s)

    # 组合 1：开场白 + 话题
    for opener in CHAT_OPENERS:
        for topic in CHAT_TOPICS:
            lines.add(f"{opener}，{topic}")

    # 组合 2：情绪开场 + 话题
    emo_openers = ["好开心啊，", "有点难过，", "吓我一跳，", "气死我了，",
                   "说起来，", "奇怪的是，", "没想到，", "有意思的是，"]
    for eo in emo_openers:
        for topic in CHAT_TOPICS:
            lines.add(eo + topic)

    # 组合 3：游戏前缀 + 游戏台词
    game_prefixes = ["诶，", "对了，", "我说，", "快来，", "哎呀，", "嗯，",
                     "说起来，", "刚才，", "你猜，", "听着，", "嘿，", "注意，"]
    for p in game_prefixes:
        for g in GAME_LINES:
            lines.add(p + g)

    # 组合 4：人设 + 话题
    for p in PERSONA:
        for t in CHAT_TOPICS[:20]:
            lines.add(p + t)

    # 组合 5：问候变体
    time_words = ["早上", "中午", "下午", "晚上", "深夜", "清晨", "傍晚"]
    greet_words = ["好呀", "好哦", "好啊", "好啦", "好"]
    suffixes = ["最近怎么样？", "吃饭了吗？", "忙什么呢？", "还好吧？",
                "精神怎么样？", "心情如何？"]
    for tw in time_words:
        for gw in greet_words:
            for suf in suffixes:
                lines.add(f"{tw}{gw}，{suf}")

    # 组合 6：互动问题 + 前缀
    q_prefixes = ["嗯，", "对了，", "说起来，", "我想问，", "顺便问下，",
                  "好奇一下，", "说真的，", "话说，", "那个，", "我问你，"]
    for q in QUESTIONS:
        for qp in q_prefixes:
            lines.add(qp + q)

    # 组合 7：知识 + 引导词
    know_lead = ["你知道吗，", "听说，", "原来，", "据说，", "据说呢，",
                 "科普一下，", "有趣的是，", "告诉你，", "我看过，", "书上说，"]
    for k in KNOWLEDGE:
        for lead in know_lead:
            lines.add(lead + k)

    # 组合 8：确认应答 + 后续话题
    for r in SHORT_REPLIES:
        for t in CHAT_TOPICS[:15]:
            lines.add(r + t)

    # 组合 9：故事开场 + 故事
    story_lead = ["给你讲个故事，", "从前，", "听好啦，", "很久以前，",
                  "我听过一个故事，", "据说，", "传说中，", "话说，"]
    for s in STORIES:
        for lead in story_lead:
            lines.add(lead + s)

    # 组合 10：节日祝福变体
    fest_prefix = ["祝你", "愿你", "希望你", "祝福你", "祝大家"]
    for f in FESTIVALS:
        for fp in fest_prefix:
            lines.add(fp + f)

    # 组合 11：记忆相关扩展
    mem_lead = ["放心，", "别担心，", "好的，", "没问题，", "嗯，",
                "交给我，", "当然，", "那是自然，"]
    for m in MEMORY_LINES:
        for lead in mem_lead:
            lines.add(lead + m)

    # 组合 12：情绪 + 人设
    for emo in EMOTION_HAPPY + EMOTION_SAD + EMOTION_SURPRISE:
        for p in PERSONA[:10]:
            lines.add(emo + p)

    # 组合 13：游戏 + 情绪
    for g in GAME_LINES[:15]:
        for emo in EMOTION_HAPPY[:3] + EMOTION_SAD[:3] + EMOTION_SURPRISE[:3]:
            lines.add(emo + g)

    # 组合 14：多轮对话感
    multi_turn = [
        "嗯，我明白了，然后呢？", "是这样啊，那后来呢？", "原来如此，继续说。",
        "真的吗？我不太信。", "哦？有意思，详细说说。", "好厉害，怎么做到的？",
        "我也是这么想的。", "不太懂，能再解释一下吗？", "原来是这样，学到了。",
        "嗯，你说得有道理。", "我赞同你的看法。", "这观点挺新颖的。",
    ]
    for mt in multi_turn:
        lines.add(mt)
        for t in CHAT_TOPICS[:8]:
            lines.add(mt + t)

    return lines


def main():
    lines = generate_corpus()
    # 过滤：长度 4~80 字，去重
    filtered = []
    seen = set()
    for line in lines:
        line = line.strip().replace(" ", "").replace("，。", "。")
        n = len(line)
        if n < 4 or n > 80:
            continue
        if line in seen:
            continue
        seen.add(line)
        filtered.append(line)

    random.shuffle(filtered)

    out_path = "corpus.txt"
    with open(out_path, "w", encoding="utf-8") as f:
        for line in filtered:
            f.write(line + "\n")

    lengths = [len(l) for l in filtered]
    total_chars = sum(lengths)
    print(f"语料生成完成：{out_path}")
    print(f"总条目：{len(filtered)}")
    print(f"长度范围：{min(lengths)}~{max(lengths)} 字")
    print(f"平均长度：{total_chars/len(filtered):.1f} 字")
    print(f"总字数：{total_chars} 字")
    print(f"预估语音时长：{total_chars*0.3/60:.0f}~{total_chars*0.35/60:.0f} 分钟")

    print("\n前 15 条样例：")
    for l in filtered[:15]:
        print(f"  {l}")


if __name__ == "__main__":
    main()

def get_ngrams(text, n=3):
    text = text.lower().strip()
    text = re.sub(r'[^\w\s]', '', text)
    return set(text[i:i+n] for i in range(len(text) - n + 1))

def text_similarity(text1, text2, n=3):
    ngrams1 = get_ngrams(text1, n)
    ngrams2 = get_ngrams(text2, n)
    if not ngrams1 or not ngrams2:
        return 0.0
    intersection = ngrams1 & ngrams2
    union = ngrams1 | ngrams2
    return len(intersection) / len(union)

def conv_text(turns):
    return " ".join(content for _, content in turns)

def clean_text(text):
    text = re.sub(r'[（(][^）)]*[）)]', '', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text

def make_msg(role, content):
    if role == "system":
        return {"role": role, "content": content}
    return {"role": role, "content": clean_text(content)}

def build_messages(turns, memory_context=None):
    system_prompt = SYSTEM_PROMPT_PATH.read_text(encoding="utf-8").strip()
    if memory_context:
        system_prompt = system_prompt + "\n\n" + memory_context.strip()
    messages = [make_msg("system", system_prompt)]
    for role, content in turns:
        messages.append(make_msg(role, content))
    return messages

def conv_signature(messages):
    sig_parts = []
    for m in messages:
        if m["role"] != "system":
            sig_parts.append(f"{m['role']}:{m['content']}")
    return hashlib.md5("||".join(sig_parts).encode("utf-8")).hexdigest()

conversations = []
seen_sigs = set()
mem_conv_indices = set()
conv_turns_cache = []
SIMILARITY_THRESHOLD = 0.6

def add_conv(turns, memory_context=None, check_similarity=True):
    if not turns:
        raise ValueError("对话turns不能为空")
    if turns[0][0] != "user":
        raise ValueError(f"对话必须以user开头，第一个角色是: {turns[0][0]}, 内容: {turns[0][1][:50]}")
    prev_role = None
    for i, (role, content) in enumerate(turns):
        if role not in ("user", "assistant"):
            raise ValueError(f"第{i}轮角色错误: {role}")
        if role == prev_role:
            raise ValueError(f"第{i}轮角色重复: {role}, 上一轮也是{role}, 内容: {content[:50]}")
        if not content or not content.strip():
            raise ValueError(f"第{i}轮内容为空")
        prev_role = role
    
    if check_similarity:
        current_text = conv_text(turns)
        for existing_turns in conv_turns_cache:
            existing_text = conv_text(existing_turns)
            sim = text_similarity(current_text, existing_text)
            if sim > SIMILARITY_THRESHOLD:
                return False
    
    msgs = build_messages(turns, memory_context)
    sig = conv_signature(msgs)
    if sig not in seen_sigs:
        seen_sigs.add(sig)
        idx = len(conversations)
        conversations.append({"messages": msgs})
        conv_turns_cache.append(turns)
        if memory_context:
            mem_conv_indices.add(idx)
        return True
    return False

